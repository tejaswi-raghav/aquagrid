"use client";

import { AnimatePresence, motion } from "motion/react";
import { useEffect, useRef, useState } from "react";
import { request, type OpsDoc } from "@/lib/operations";

export type AnalystTurn = {
  role: "user" | "assistant";
  content: string;
  trace?: { tool: string; args: Record<string, unknown>; ok: boolean; status?: string | null }[];
  model?: string;
  error?: boolean;
};

type AskResponse = { reply: string; trace: NonNullable<AnalystTurn["trace"]>; model: string; doc: OpsDoc | null };

const SUGGESTIONS = [
  "What's going wrong right now, and what's the evidence?",
  "Electricity is expensive. Cut production to save money.",
  "Should we close V-04B? What's the trade-off?",
  "Approve the valve isolation for me.",
];

const TOOL_COPY: Record<string, string> = {
  get_situation: "Read live telemetry",
  compare_production_plans: "Compared production plans",
  preview_valve: "Previewed valve",
  stage_proposal: "Staged proposal",
};

function traceLabel(t: NonNullable<AnalystTurn["trace"]>[number]) {
  const base = TOOL_COPY[t.tool] ?? t.tool;
  const target = (t.args.valve_id as string) || (t.args.plan as string) || "";
  return `${base}${target ? ` · ${target}` : ""}`;
}

/** Renders the model's light markdown (bold, bullet lines) as React nodes, never as HTML. */
function bold(line: string) {
  return line.split(/(\*\*[^*]+\*\*)/g).map((part, i) =>
    part.startsWith("**") && part.endsWith("**") && part.length > 4 ? <strong key={i}>{part.slice(2, -2)}</strong> : part);
}
function Rich({ text }: { text: string }) {
  const blocks: React.ReactNode[] = [];
  let items: string[] = [];
  const flush = () => { if (items.length) { blocks.push(<ul key={blocks.length}>{items.map((x, i) => <li key={i}>{bold(x)}</li>)}</ul>); items = []; } };
  for (const raw of text.split("\n")) {
    const line = raw.trim();
    const bullet = line.match(/^(?:[-*•]|\d+[.)])\s+(.*)$/);
    if (bullet) { items.push(bullet[1]); continue; }
    flush();
    if (line) blocks.push(<p key={blocks.length}>{bold(line.replace(/^#+\s*/, ""))}</p>);
  }
  flush();
  return <>{blocks}</>;
}

export function AnalystPanel({ doc, turns, setTurns, onDoc, onOpenQueue }: {
  doc: OpsDoc; turns: AnalystTurn[]; setTurns: (fn: (t: AnalystTurn[]) => AnalystTurn[]) => void;
  onDoc: (d: OpsDoc) => void; onOpenQueue: () => void;
}) {
  const [draft, setDraft] = useState("");
  const [thinking, setThinking] = useState(false);
  const log = useRef<HTMLDivElement>(null);

  useEffect(() => { log.current?.scrollTo({ top: log.current.scrollHeight, behavior: "smooth" }); }, [turns, thinking]);

  async function send(text: string) {
    const content = text.trim();
    if (!content || thinking) return;
    const history = [...turns.filter((t) => !t.error), { role: "user" as const, content }];
    setTurns((t) => [...t, { role: "user", content }]);
    setDraft(""); setThinking(true);
    try {
      const r = await request<AskResponse>("ask", {
        scenario_id: doc.id,
        messages: history.slice(-12).map(({ role, content }) => ({ role, content: content.slice(0, 4000) })),
      });
      if (r.doc) onDoc(r.doc);
      setTurns((t) => [...t, { role: "assistant", content: r.reply, trace: r.trace, model: r.model }]);
    } catch (e) {
      setTurns((t) => [...t, { role: "assistant", error: true, content: e instanceof Error ? e.message : "The AI analyst is unavailable." }]);
    } finally { setThinking(false); }
  }

  return (
    <div className="ops-detail-grid analyst-grid">
      <article>
        <p className="ops-overline">AI analyst · LLM</p>
        <h2>Ask in plain English. It proposes; you decide.</h2>
        <p>
          The analyst reads the same engine you see here and can stage proposals into the approval queue.
          It has no approve button: the server re-checks every safety rule, and only a signed-in operator can authorize.
        </p>
        <h3>Try asking</h3>
        <div className="analyst-suggestions">
          {SUGGESTIONS.map((s) => <button type="button" key={s} disabled={thinking} onClick={() => send(s)}>{s}</button>)}
        </div>
        <p className="ops-muted">Answers are generated by a language model and can be wrong. Numbers come from tool results; check them against the panels.</p>
      </article>

      <article className="analyst-chat">
        <div className="analyst-log" ref={log} aria-live="polite">
          {turns.length === 0 && !thinking && (
            <p className="analyst-empty">No questions yet. Trigger the 14:00 disruption first for something to investigate.</p>
          )}
          <AnimatePresence initial={false}>
            {turns.map((t, i) => (
              <motion.div key={i} className={`analyst-msg ${t.role} ${t.error ? "is-error" : ""}`}
                initial={{ opacity: 0, y: 8 }} animate={{ opacity: 1, y: 0 }} transition={{ duration: 0.2 }}>
                {t.trace && t.trace.length > 0 && (
                  <ul className="analyst-trace" aria-label="What the analyst checked">
                    {t.trace.map((x, j) => (
                      <li key={j} className={!x.ok ? "bad" : x.status === "BLOCKED_BY_SAFETY" ? "blocked" : x.status === "PENDING_APPROVAL" ? "pending" : ""}>
                        {traceLabel(x)}
                        {x.status && <b>{x.status === "BLOCKED_BY_SAFETY" ? "blocked by safety" : "awaiting operator"}</b>}
                        {!x.ok && <b>tool error</b>}
                      </li>
                    ))}
                  </ul>
                )}
                {t.role === "assistant" && !t.error ? <Rich text={t.content} /> : <p>{t.content}</p>}
                {t.trace?.some((x) => x.tool === "stage_proposal" && x.ok) && (
                  <button type="button" className="link-btn" onClick={onOpenQueue}>Open the approval queue</button>
                )}
              </motion.div>
            ))}
          </AnimatePresence>
          {thinking && <div className="analyst-msg assistant thinking"><span /><span /><span /></div>}
        </div>
        <form className="analyst-form" onSubmit={(e) => { e.preventDefault(); void send(draft); }}>
          <label className="sr-only" htmlFor="analyst-input">Ask the AI analyst</label>
          <input id="analyst-input" value={draft} onChange={(e) => setDraft(e.target.value)} maxLength={1000}
            placeholder="Ask about the leak, the plans or a valve…" disabled={thinking} autoComplete="off" />
          <button type="submit" className="primary" disabled={thinking || !draft.trim()}>Ask</button>
        </form>
      </article>
    </div>
  );
}
